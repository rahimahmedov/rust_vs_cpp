// ─────────────────────────────────────────────────────────────────────────────
// Section 3 — Multiple Inheritance and Composition
// ─────────────────────────────────────────────────────────────────────────────

class Drawable {
public:
    virtual ~Drawable() = default;
    virtual void draw() const = 0;
};

class Resizable {
public:
    virtual ~Resizable() = default;
    virtual void resize(double factor) = 0;
};

// Multiple inheritance — C++ allows it, but the diamond problem lurks
class DrawableRect : public RectangleShape, public Drawable, public Resizable {
public:
    DrawableRect(double w, double h) : RectangleShape(w, h) {}

    void draw() const override {
        std::cout << "    [drawing rectangle " << width() << "x" << height() << "]\n";
    }
    void resize(double factor) override { scale(factor); }
};

// Composition — preferred in both C++ and Rust to avoid diamond problems
// Rust: struct ColoredShape<S: Shape + Drawable> { shape: S, color: String }
template <typename S>  // S must be a Shape and Drawable
class ColoredShape {
public:
    ColoredShape(S shape, std::string color)
        : shape_(std::move(shape)), color_(std::move(color)) {}

    void draw_colored() const {
        std::cout << "    color=" << color_ << " ";
        shape_.draw();
    }
    double area()      const { return shape_.area(); }
    double perimeter() const { return shape_.perimeter(); }

private:
    S           shape_;
    std::string color_;
};

static void section3_composition() {
    std::cout << "=== Section 3: Multiple Inheritance and Composition ===\n";
    std::cout << "C++: multiple inheritance (diamond problem possible).\n";
    std::cout << "Rust: multiple trait impls + composition (no diamond problem).\n\n";

    DrawableRect dr(4.0, 3.0);
    std::cout << "  DrawableRect implements Shape + Drawable + Resizable:\n";
    std::cout << "    area=" << dr.area() << "  perimeter=" << dr.perimeter() << "\n";
    dr.draw();
    dr.resize(2.0);
    std::cout << "    after resize(2.0): area=" << dr.area() << "\n";

    std::cout << "\n  Composition — ColoredShape<DrawableRect>:\n";
    ColoredShape<DrawableRect> colored(DrawableRect(5.0, 2.0), "red");
    colored.draw_colored();
    std::cout << "    area (delegated): " << colored.area() << "\n";

    std::cout << "\n  Diamond problem:\n";
    std::cout << "    C++: class D : public B, public C where B and C both derive A\n";
    std::cout << "         causes ambiguity; need virtual inheritance to resolve.\n";
    std::cout << "    Rust: no state in traits — diamond problem cannot occur.\n";
    std::cout << "          If two traits define the same method, you qualify explicitly:\n";
    std::cout << "          Trait1::method(&x)  or  Trait2::method(&x)\n\n";
}

// ─────────────────────────────────────────────────────────────────────────────
// Section 4 — Templates
// ─────────────────────────────────────────────────────────────────────────────

// C++ template: UNCONSTRAINED by default — errors appear at instantiation.
// C++17: no constraint syntax; rely on SFINAE or static_assert.
// C++20: concepts provide compile-time bounds (closest to Rust trait bounds).

// C++17 unconstrained template — Rust equivalent: fn largest<T: PartialOrd>
// Error only if T doesn't support > — at CALL SITE, not here
template <typename T>
const T& largest(const std::vector<T>& list) {
    assert(!list.empty());
    const T* biggest = &list[0];
    for (const T& item : list) {
        if (item > *biggest) biggest = &item;
    }
    return *biggest;
}

// Generic struct — Rust: struct Pair<T, U> { first: T, second: U }
template <typename T, typename U>
struct Pair {
    T first;
    U second;

    Pair(T f, U s) : first(std::move(f)), second(std::move(s)) {}

    // Conditional method: available only when T and U are comparable and printable.
    // C++17: use if constexpr or SFINAE. C++20: use requires.
    // Rust: impl<T, U> Pair<T, U> where T: Display + PartialOrd, U: Display + PartialOrd
    void cmp_display() const {
        std::cout << "    first=" << first
                  << (first >= second ? " >= " : " < ")
                  << "second=" << second << "\n";
    }
};

// C++17 template function with multiple concept-like constraints via static_assert
// Rust: fn print_shape_info<T: Shape + Debug>(shape: &T)
template <typename T>
void print_shape_info(const T& shape) {
    // In C++17 there's no compile-time guarantee T has .name()/.area()
    // — errors only if T doesn't have those methods, at instantiation
    std::cout << "    " << shape.name() << " → area=" << shape.area() << "\n";
}

