// ─────────────────────────────────────────────────────────────────────────────
// Section 5 — Virtual (Dynamic) vs Template (Static) Dispatch
// ─────────────────────────────────────────────────────────────────────────────

// Template (static) dispatch — Rust: fn f<T: Shape>(shapes: &[T])
// Compiler instantiates a separate function per T. Zero vtable overhead.
template <typename T>
double total_area_static(const std::vector<T>& shapes) {
    double total = 0.0;
    for (const T& s : shapes) total += s.area();
    return total;
}

// Virtual (dynamic) dispatch — Rust: fn f(shapes: &[Box<dyn Shape>])
// Each call goes through the vtable. Required for heterogeneous collections.
static double total_area_dynamic(const std::vector<std::unique_ptr<Shape>>& shapes) {
    double total = 0.0;
    for (const auto& s : shapes) total += s->area();
    return total;
}

static void print_all(const std::vector<std::unique_ptr<Shape>>& shapes) {
    for (const auto& s : shapes) {
        std::cout << "    " << s->describe() << "\n";
    }
}

static void section5_dispatch() {
    std::cout << "=== Section 5: Static Dispatch vs Dynamic (Virtual) Dispatch ===\n\n";

    // Static dispatch via templates
    std::cout << "  Static dispatch — template instantiation per type:\n";
    std::cout << "    Compiler generates a separate total_area_static for each T.\n";
    std::cout << "    Zero runtime overhead — identical to Rust static dispatch.\n\n";

    std::vector<Circle> circles = { Circle(1.0), Circle(2.0), Circle(3.0) };
    std::cout << "    total_area_static([Circle×3]) = "
              << total_area_static(circles) << "\n";

    // Dynamic dispatch via virtual
    std::cout << "\n  Dynamic dispatch — vtable pointer per object:\n";
    std::cout << "    Every virtual call = one pointer dereference (vtable lookup).\n";
    std::cout << "    Rust: &dyn Shape / Box<dyn Shape> — same mechanism, explicit opt-in.\n";
    std::cout << "    C++: ALL virtual calls are dynamic — no way to opt for static.\n";
    std::cout << "    Required for mixing different concrete types in one collection.\n\n";

    std::vector<std::unique_ptr<Shape>> shapes;
    shapes.push_back(std::make_unique<RectangleShape>(3.0, 4.0));
    shapes.push_back(std::make_unique<Circle>(2.0));
    shapes.push_back(std::make_unique<Triangle>(3.0, 4.0, 5.0));

    print_all(shapes);
    std::cout << "    total_area_dynamic (mixed vec) = "
              << total_area_dynamic(shapes) << "\n";

    std::cout << "\n  Summary — static vs dynamic dispatch:\n";
    std::cout << "    C++   static:  template<T> — no vtable, inlinable, T must be uniform\n";
    std::cout << "    C++   dynamic: virtual     — vtable, heterogeneous collections OK\n";
    std::cout << "    Rust  static:  <T: Trait>  — no vtable, inlinable (default choice)\n";
    std::cout << "    Rust  dynamic: dyn Trait   — vtable, explicit, heterogeneous OK\n";
    std::cout << "    Rust forces you to consciously choose; C++ virtual is always dynamic.\n";
}

